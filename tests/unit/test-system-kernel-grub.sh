write_grub_cfg() {
    local default_value="$1" first_release="${2:-7.1.11-x64v3-xanmod1}"
    mkdir -p "$TEST_SYSTEM_ROOT/boot/grub"
    cat >"$KERNEL_GRUB_CFG" <<EOF
# DO NOT EDIT THIS FILE
# generated by grub-mkconfig
set default="$default_value"
### BEGIN /etc/grub.d/10_linux ###
menuentry 'Debian GNU/Linux' --class debian \$menuentry_id_option 'gnulinux-simple-UUID' {
    linux /boot/vmlinuz-$first_release root=UUID=root-a ro
}
submenu 'Advanced options for Debian GNU/Linux' \$menuentry_id_option 'gnulinux-advanced-UUID' {
    menuentry 'Debian GNU/Linux, with Linux 6.12.12-amd64' \$menuentry_id_option 'gnulinux-6.12.12-amd64-advanced-UUID' {
        linux /boot/vmlinuz-6.12.12-amd64 root=UUID=root-a ro
    }
    menuentry 'Debian GNU/Linux, with Linux 6.12.12-amd64 (recovery mode)' \$menuentry_id_option 'gnulinux-6.12.12-amd64-recovery-UUID' {
        linux /boot/vmlinuz-6.12.12-amd64 root=UUID=root-a ro single
    }
    menuentry 'Debian GNU/Linux, with Linux 6.12.9-amd64' \$menuentry_id_option 'gnulinux-6.12.9-amd64-advanced-UUID' {
        linux /boot/vmlinuz-6.12.9-amd64 root=UUID=root-a ro
    }
    menuentry 'Debian GNU/Linux, with Linux 7.1.11-x64v3-xanmod1' \$menuentry_id_option 'gnulinux-7.1.11-x64v3-xanmod1-advanced-UUID' {
        linux /boot/vmlinuz-7.1.11-x64v3-xanmod1 root=UUID=root-a ro
    }
}
### END /etc/grub.d/10_linux ###
EOF
}

write_defaults() {
    local value="$1"
    mkdir -p "$TEST_SYSTEM_ROOT/etc/default/grub.d"
    printf "GRUB_DEFAULT='%s'\nGRUB_SAVEDEFAULT=false\n" "$value" >"$KERNEL_GRUB_DEFAULT_FILE"
}

write_env() {
    mkdir -p "${KERNEL_GRUB_ENV%/*}"
    {
        printf '# GRUB Environment Block\n'
        printf '%s\n' "$@"
        printf '########################################\n'
    } >"$KERNEL_GRUB_ENV"
}

reset_fixture() {
    rm -rf -- "$TEST_SYSTEM_ROOT"
    mkdir -p \
        "$TEST_SYSTEM_ROOT/etc/default/grub.d" \
        "$TEST_SYSTEM_ROOT/boot/grub" \
        "$TEST_SYSTEM_ROOT/var/lib/vpsctl/system/kernel"
    vps_cmd_init system-kernel-grub "$TEST_ROOT"
    kernel_grub_init_paths
    write_defaults 0
    write_grub_cfg 0
    write_env
    VPSCTL_DRY_RUN=0
    KERNEL_RELEASE_COMPLETE["6.12.12-amd64"]=1
}

