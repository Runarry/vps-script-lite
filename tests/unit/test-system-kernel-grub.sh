update_grub_fixture() (
    local GRUB_DEFAULT=0 file
    # Match update-grub's order using only trusted fixture assignments.
    for file in "$KERNEL_GRUB_DEFAULT_FILE" "$KERNEL_GRUB_DEFAULT_DIR"/*.cfg; do
        [[ -f "$file" ]] || continue
        # shellcheck source=/dev/null
        source "$file"
    done
    [[ "$GRUB_DEFAULT" != saved ]] || GRUB_DEFAULT='${saved_entry}'
    sed -i "s|^set default=.*|set default=\"${GRUB_DEFAULT}\"|" "$KERNEL_GRUB_CFG"
)

grub_editenv_fixture() {
    local file="$1" operation="$2" key="$3" temporary
    [[ "$operation" == unset && "$key" == next_entry ]] || return 1
    temporary="${file}.new"
    awk -F= '$1 != "next_entry" {print}' "$file" >"$temporary"
    mv -- "$temporary" "$file"
}

test_switch_success() {
    local output status=0 stable order="$TEST_TEMP/action-order"
    reset_fixture
    stable='gnulinux-advanced-UUID>gnulinux-7.1.11-x64v3-xanmod1-advanced-UUID'
    write_env 'next_entry=1>2'
    update-grub() {
        printf 'update\n' >>"$order"
        update_grub_fixture
    }
    grub-editenv() {
        printf 'unset\n' >>"$order"
        grub_editenv_fixture "$@"
    }
    output="$(kernel_grub_switch 7.1.11-x64v3-xanmod1 2>&1)" || status=$?
    assert_equal 0 "$status" 'persistent switch'
    grep -Fqx "$KERNEL_MANAGED_MARKER" "$KERNEL_GRUB_DROPIN" || test_fail 'managed marker missing'
    grep -Fqx "GRUB_DEFAULT='$stable'" "$KERNEL_GRUB_DROPIN" || test_fail 'stable default missing'
    grep -Fqx 'GRUB_SAVEDEFAULT=false' "$KERNEL_GRUB_DROPIN" || test_fail 'savedefault was not disabled'
    ! grep -q '^next_entry=' "$KERNEL_GRUB_ENV" || test_fail 'next_entry was not cleared'
    assert_equal $'unset\nupdate' "$(<"$order")" 'next_entry cleared before GRUB generation'
    assert_contains "$output" '未自动重启' 'no automatic reboot message'
    [[ -d "$KERNEL_GRUB_BACKUP_ROOT" ]] || test_fail 'backup root missing'
    [[ "$(find "$KERNEL_GRUB_BACKUP_ROOT" -mindepth 1 -maxdepth 1 -type d | wc -l)" == 1 ]] || test_fail 'unique backup missing'

    write_grub_cfg "$stable" 6.12.9-amd64
    kernel_grub_load
    assert_equal 1 "$KERNEL_GRUB_SUPPORTED" 'stable pin remains supported after the first menu kernel changes'
    assert_equal 7.1.11-x64v3-xanmod1 "$KERNEL_GRUB_DEFAULT_RELEASE" 'stable pin survives a changed generic menu entry'
    assert_equal "$stable" "$KERNEL_GRUB_DEFAULT_ID" 'stable pin keeps the exact entry ID'
    assert_equal "$stable" "$KERNEL_GRUB_RAW_DEFAULT" 'stable pin keeps the literal default'
    assert_equal false "$KERNEL_GRUB_RAW_SAVEDEFAULT" 'stable pin keeps savedefault disabled'
}

test_switch_override_rollback() {
    local stable='gnulinux-advanced-UUID>gnulinux-7.1.11-x64v3-xanmod1-advanced-UUID'
    local override prior output status expected_default expected_id expected_save
    local old_cfg old_env old_dropin old_foreign foreign
    update-grub() { update_grub_fixture; }
    grub-editenv() { grub_editenv_fixture "$@"; }
    for override in numeric generic saved savedefault; do
        for prior in absent managed; do
            reset_fixture
            if [[ "$prior" == managed ]]; then
                printf '%s\n' "$KERNEL_MANAGED_MARKER" "GRUB_DEFAULT='1>0'" 'GRUB_SAVEDEFAULT=false' >"$KERNEL_GRUB_DROPIN"
                old_dropin="$(sha256sum "$KERNEL_GRUB_DROPIN")"
            fi
            foreign="$KERNEL_GRUB_DEFAULT_DIR/zz-existing.cfg"
            expected_id="$stable"
            expected_save=false
            case "$override" in
                numeric)
                    expected_default=0
                    expected_id=gnulinux-simple-UUID
                    printf 'GRUB_DEFAULT=0\n' >"$foreign"
                    ;;
                generic)
                    expected_default=gnulinux-simple-UUID
                    expected_id=gnulinux-simple-UUID
                    printf 'GRUB_DEFAULT=%s\n' "$expected_default" >"$foreign"
                    ;;
                saved)
                    expected_default=saved
                    printf 'GRUB_DEFAULT=saved\n' >"$foreign"
                    ;;
                savedefault)
                    expected_default="$stable"
                    expected_save=true
                    printf 'GRUB_SAVEDEFAULT=true\n' >"$foreign"
                    ;;
            esac
            write_env "saved_entry=$stable" 'next_entry=1>2'
            update_grub_fixture
            old_cfg="$(sha256sum "$KERNEL_GRUB_CFG")"
            old_env="$(sha256sum "$KERNEL_GRUB_ENV")"
            old_foreign="$(sha256sum "$foreign")"
            status=0
            output="$(kernel_grub_switch 7.1.11-x64v3-xanmod1 2>&1)" || status=$?
            assert_equal 20 "$status" "$override override with $prior managed drop-in rejects a false success"
            assert_contains "$output" 'GRUB 更新后回读验证失败' "$override override reports readback failure"
            assert_contains "$output" "预期 GRUB_DEFAULT='$stable'、默认 ID='$stable'、GRUB_SAVEDEFAULT=false" "$override expected pin diagnostic"
            assert_contains "$output" "实际 GRUB_DEFAULT='$expected_default'、默认 ID='$expected_id'、GRUB_SAVEDEFAULT='$expected_save'" "$override effective pin diagnostic"
            [[ "$output" != *'已将下次及后续启动永久固定'* ]] || test_fail "$override override reported a successful pin"
            assert_equal "$old_cfg" "$(sha256sum "$KERNEL_GRUB_CFG")" "$override rollback grub.cfg"
            assert_equal "$old_env" "$(sha256sum "$KERNEL_GRUB_ENV")" "$override rollback grubenv"
            assert_equal "$old_foreign" "$(sha256sum "$foreign")" "$override preserves the foreign override"
            if [[ "$prior" == managed ]]; then
                assert_equal "$old_dropin" "$(sha256sum "$KERNEL_GRUB_DROPIN")" "$override restores the old managed drop-in"
            else
                [[ ! -e "$KERNEL_GRUB_DROPIN" ]] || test_fail "$override rollback left a newly-created drop-in"
            fi
        done
    done
}

test_transaction_rollback() {
    local old_cfg old_env status=0 counter="$TEST_TEMP/update-count"
    reset_fixture
    write_env 'saved_entry=gnulinux-simple-UUID' 'next_entry=1>2'
    old_cfg="$(sha256sum "$KERNEL_GRUB_CFG")"
    old_env="$(sha256sum "$KERNEL_GRUB_ENV")"
    update-grub() {
        local count=0
        [[ ! -f "$counter" ]] || read -r count <"$counter"
        count=$((count + 1))
        printf '%s\n' "$count" >"$counter"
        ((count > 1)) || return 1
        update_grub_fixture
    }
    grub-editenv() { grub_editenv_fixture "$@"; }
    kernel_grub_switch 6.12.12-amd64 >/dev/null 2>&1 || status=$?
    assert_equal 20 "$status" 'failed update with verified rollback'
    [[ ! -e "$KERNEL_GRUB_DROPIN" ]] || test_fail 'rollback left newly-created drop-in'
    assert_equal "$old_cfg" "$(sha256sum "$KERNEL_GRUB_CFG")" 'rollback grub.cfg'
    assert_equal "$old_env" "$(sha256sum "$KERNEL_GRUB_ENV")" 'rollback grubenv'
    grep -Fqx 'next_entry=1>2' "$KERNEL_GRUB_ENV" || test_fail 'rollback did not restore old next_entry'
    [[ "$(<"$counter")" == 2 ]] || test_fail 'rollback did not regenerate GRUB'

    reset_fixture
    old_cfg="$(sha256sum "$KERNEL_GRUB_CFG")"
    update-grub() { return 1; }
    status=0
    kernel_grub_switch 6.12.12-amd64 >/dev/null 2>&1 || status=$?
    assert_equal 30 "$status" 'rollback regeneration failure is critical'
    assert_equal "$old_cfg" "$(sha256sum "$KERNEL_GRUB_CFG")" 'critical rollback still restores generated file bytes'
}

