    assert_equal "$before_env" "$(sha256sum "$KERNEL_GRUB_ENV")" 'dry-run grubenv unchanged'
    [[ ! -e "$KERNEL_GRUB_DROPIN" && ! -e "$KERNEL_GRUB_BACKUP_ROOT" ]] || test_fail 'dry-run created managed state'

