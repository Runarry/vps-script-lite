            printf 'seed:suppress\n' >>"$log"
        else
            printf 'seed:persist\n' >>"$log"
        fi
    }
    debconf-communicate() {
        local request question value
        request="$(cat)"
        [[ "$request" == 'GET grub-pc/'* ]] || return 97
        question="${request#GET }"
        value="$(awk -v question="$question" '$2 == question && ($3 == "multiselect" || $3 == "boolean") {sub(/^[^ ]+ [^ ]+ [^ ]+ /, ""); print; exit}' "$seed")"
        if [[ "$test_execute_case" == debconf-drift && "$question" == grub-pc/install_devices ]]; then
            printf '0 /dev/old-wrong-disk\n'
        elif [[ "$test_execute_case" == debconf-flag-drift && "$question" == grub-pc/install_devices_failed_upgrade ]]; then
            printf '0 true\n'
        elif [[ "$test_execute_case" == cloud-auto-drift && "$question" == grub-pc/cloud_style_installation ]]; then
            printf '0 true\n'
        else
            printf '0 %s\n' "$value"
        fi
    }
    _kernel_grub_install_probe_disk() {
        assert_equal /dev/vda "$1" 'post-install disk inspection uses confirmed device'
        [[ "$test_execute_case" != table-drift ]] || KERNEL_GRUB_INSTALL_TABLE_DATA=changed
    }
    _kernel_grub_install_run() {
        local argument selected=0
        case "$1" in
            env)
                printf 'apt\n' >>"$log"
                grep -Fqx 'grub-pc grub-pc/install_devices multiselect ' "$seed" || test_fail 'package hooks retained an old install disk'
                grep -Fqx 'grub-pc grub-pc/install_devices_disks_changed multiselect ' "$seed" || test_fail 'package hooks retained a changed-disk fallback'
                grep -Fqx 'grub-pc grub-pc/install_devices_empty boolean true' "$seed" || test_fail 'package hooks may prompt or write a guessed disk'
                grep -Fqx 'grub-pc grub-pc/install_devices_failed boolean false' "$seed" || test_fail 'package hook failures may be ignored'
                grep -Fqx 'grub-pc grub-pc/cloud_style_installation boolean false' "$seed" || test_fail 'Ubuntu cloud package hooks may bypass explicit install_devices'
