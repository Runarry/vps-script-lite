        printf 'grub-pc grub-pc/install_devices multiselect /dev/old-wrong-disk\n' >"$seed"
        printf 'grub-pc grub-pc/cloud_style_installation boolean true\n' >>"$seed"
        KERNEL_GRUB_INSTALL_DISK=/dev/vda
        KERNEL_GRUB_INSTALL_TABLE_DATA=unchanged
        KERNEL_GRUB_INSTALL_BACKUP="$KERNEL_GRUB_BACKUP_ROOT/execute-fixture"
        mkdir -p "$KERNEL_GRUB_INSTALL_BACKUP"
        KERNEL_GRUB_INSTALL_ARGS=(grub-pc=2.12-9)
        KERNEL_GRUB_INSTALL_EXPECTED_VERSIONS=(['grub-pc']=2.12-9)
        for package in grub-pc grub-pc-bin grub-common grub2-common; do
            KERNEL_PKG_STATUS[$package]='ii '
            KERNEL_PKG_VERSION[$package]=2.12-9
