load_disk_fixture() {
    local mode="$1"
    DISK_ROOT_JSON="$(disk_fixture_field "$mode" root)"
    DISK_BOOT_JSON="$(disk_fixture_field "$mode" boot)"
    DISK_LSBLK_JSON="$(disk_fixture_field "$mode" lsblk)"
    DISK_TABLE_JSON="$(disk_fixture_field "$mode" table)"
    DISK_MBR_HEX="$(disk_fixture_field "$mode" mbr)"
    DISK_REQUESTED="$(disk_fixture_field "$mode" requested)"
}

parse_disk_fixture() {
    _kernel_grub_install_parse_disk_data "$DISK_REQUESTED" "$DISK_ROOT_JSON" "$DISK_BOOT_JSON" \
        "$DISK_LSBLK_JSON" "$DISK_TABLE_JSON" "$DISK_MBR_HEX"
}

test_disk_json_safety() (
    local mode output
    for mode in mbr separate-boot extra-data-disk nvme gpt; do
        load_disk_fixture "$mode"
        output="$(parse_disk_fixture)" || test_fail "$mode valid disk layout rejected"
        assert_contains "$output" "$DISK_REQUESTED" "$mode retains the selected disk identity"
    done
    load_disk_fixture extra-data-disk
    output="$(_kernel_grub_install_parse_disk_data '' "$DISK_ROOT_JSON" "$DISK_BOOT_JSON" "$DISK_LSBLK_JSON")"
    assert_equal /dev/vda "$output" 'extra data disk does not obscure the root disk recommendation'

    for mode in wrong-disk partition-target readonly-disk readonly-root unsupported-fs lvm raid crypt \
        multipath cross-disk small-gap table-disagreement missing-source ambiguous-root bad-sector \
        gpt-small gpt-mounted gpt-formatted gpt-missing gpt-duplicate gpt-data-out-of-bounds; do
        load_disk_fixture "$mode"
        assert_rejected "$mode layout is refused before writes" parse_disk_fixture
    done
    load_disk_fixture mbr
    DISK_ROOT_JSON='{"filesystems":['
    assert_rejected 'malformed findmnt JSON is refused' parse_disk_fixture
    load_disk_fixture mbr
    DISK_LSBLK_JSON='{"blockdevices":null}'
    assert_rejected 'missing lsblk devices is refused' parse_disk_fixture
    load_disk_fixture mbr
    DISK_TABLE_JSON='{}'
    assert_rejected 'missing partition-table evidence is refused' parse_disk_fixture
)

test_default_and_next_repair_plan() (
    reset_fixture
    kernel_inventory_load() { return 0; }
    _kernel_grub_install_plan_defaults || test_fail 'valid default plan rejected'
    assert_equal 7.2.4-x64v3-xanmod1 "$KERNEL_GRUB_INSTALL_DEFAULT_RELEASE" 'existing default semantics preserved despite a different running kernel'
    assert_equal 0 "$KERNEL_GRUB_INSTALL_FALLBACK" 'resolvable default does not fall back'

    write_grub_fixture '1>1'
    write_env_fixture 'next_entry=0'
    _kernel_grub_install_plan_defaults || test_fail 'valid one-time override plan rejected'
    assert_equal 6.12.12-amd64 "$KERNEL_GRUB_INSTALL_DEFAULT_RELEASE" 'numeric submenu default preserves its target'
    assert_equal 7.2.4-x64v3-xanmod1 "$KERNEL_GRUB_INSTALL_NEXT_RELEASE" 'valid numeric one-time override preserves its target'
    assert_equal 0 "$KERNEL_GRUB_INSTALL_CLEAR_NEXT" 'valid override will be retained'

    write_grub_fixture '1>1'
    write_env_fixture 'next_entry=unknown-menu-entry'
    _kernel_grub_install_plan_defaults || test_fail 'unresolved override should produce a repair plan'
    assert_equal 6.12.12-amd64 "$KERNEL_GRUB_INSTALL_DEFAULT_RELEASE" 'valid default retained when only next override is broken'
    assert_equal 0 "$KERNEL_GRUB_INSTALL_FALLBACK" 'invalid next override does not unnecessarily change default'
    assert_equal 1 "$KERNEL_GRUB_INSTALL_CLEAR_NEXT" 'unresolvable override is explicitly scheduled for removal'

    write_grub_fixture missing-default
    write_env_fixture 'next_entry=0'
    _kernel_grub_install_plan_defaults || test_fail 'unknown default should explicitly fall back to complete running kernel'
    assert_equal 6.12.12-amd64 "$KERNEL_GRUB_INSTALL_DEFAULT_RELEASE" 'unknown default falls back to running kernel'
    assert_equal 1 "$KERNEL_GRUB_INSTALL_FALLBACK" 'fallback is exposed on confirmation plan'
    assert_equal 1 "$KERNEL_GRUB_INSTALL_CLEAR_NEXT" 'default fallback clears even a valid prior one-time override'

    KERNEL_RELEASE_COMPLETE["6.12.12-amd64"]=0
    assert_rejected 'incomplete running kernel cannot be a fallback boot target' _kernel_grub_install_plan_defaults
    KERNEL_RELEASE_COMPLETE["6.12.12-amd64"]=1
    write_grub_fixture 0
    printf 'GRUB_DEFAULT=foreign\n' >"$KERNEL_GRUB_DROPIN"
    assert_status 10 'unmanaged conflicting drop-in is not overwritten' _kernel_grub_install_validate_paths
)

test_apt_plan_trust_and_scope() (
    local test_apt_case=valid package output log="$TEST_TEMP/apt-grub-plan.log"
    reset_fixture
    : >"$log"
    apt-get() {
        local test_efi_version
        printf '%s\n' "$(kernel_join_values "$@")" >>"$log"
        case "${1:-}" in
            indextargets)
                printf '%s\n' \
                    'Description: https://deb.debian.org/debian trixie/main amd64 Packages' \
                    'Identifier: Packages' 'Codename: trixie' 'Suite: stable' 'Release: trixie' \
                    'Origin: Debian' 'Label: Debian'
                if [[ "$test_apt_case" == untrusted-index ]]; then printf 'Trusted: no\n'; else printf 'Trusted: yes\n'; fi
                printf '\n'
                ;;
            --simulate)
                [[ "$*" == *APT::Get::AutomaticRemove=false* && "$*" == *--no-remove* && "$*" == *--no-install-recommends* ]] || return 97
                case "$test_apt_case" in
                    failure) return 100 ;;
                    no-changes)
                        printf '0 upgraded, 0 newly installed, 0 to remove.\n'
                        return 0
                        ;;
                    removal)
                        printf 'Remv libc6 [2.41]\n'
                        return 0
                        ;;
                    orphan-conf)
                        printf 'Conf grub-common (2.12-9 Debian:13/stable [amd64])\n'
                        return 0
                        ;;
                esac
                for package in grub-common grub2-common grub-pc-bin grub-pc libefiboot1; do
                    [[ "$test_apt_case" != efi-modules-without-common || "$package" != grub-common ]] || continue
                    printf 'Inst %s (2.12-9 Debian:13/stable [amd64])\n' "$package"
                    printf 'Conf %s (2.12-9 Debian:13/stable [amd64])\n' "$package"
                done
                if [[ "$test_apt_case" == kernel-change ]]; then
                    printf 'Inst linux-image-6.12.14-amd64 (2.12-9 Debian:13/stable [amd64])\n'
                elif [[ "$test_apt_case" == efi-change ]]; then
                    printf 'Inst grub-efi-amd64 (2.12-9 Debian:13/stable [amd64])\n'
                fi
                if [[ "$test_apt_case" == efi-modules-* ]]; then
                    for package in grub-efi-amd64-bin grub-efi-amd64-unsigned; do
                        test_efi_version=2.12-9
                        if [[ "$test_apt_case" == efi-modules-bin-mismatch && "$package" == grub-efi-amd64-bin ]] ||
                            [[ "$test_apt_case" == efi-modules-unsigned-mismatch && "$package" == grub-efi-amd64-unsigned ]]; then
                            test_efi_version=2.12-10
                        fi
                        printf 'Inst %s (%s Debian:13/stable [amd64])\n' "$package" "$test_efi_version"
                        printf 'Conf %s (%s Debian:13/stable [amd64])\n' "$package" "$test_efi_version"
                    done
                    case "$test_apt_case" in
                        efi-modules-backend) printf 'Inst grub-efi-amd64 (2.12-9 Debian:13/stable [amd64])\n' ;;
                        efi-modules-signed) printf 'Inst grub-efi-amd64-signed (2.12-9 Debian:13/stable [amd64])\n' ;;
                        efi-modules-shim) printf 'Inst shim-signed (2.12-9 Debian:13/stable [amd64])\n' ;;
                    esac
                fi
                ;;
            *) test_fail "package planning attempted an unexpected APT operation: $*" ;;
        esac
    }
    apt-cache() {
        [[ "${1:-}" == policy ]] || return 97
        local queried="$2" source='https://deb.debian.org/debian trixie/main amd64 Packages' policy_version=2.12-9
        if [[ "$test_apt_case" == foreign-request && "$queried" == grub-pc ]] ||
            [[ "$test_apt_case" == foreign-dependency && "$queried" == libefiboot1 ]] ||
            [[ "$test_apt_case" == efi-modules-foreign && "$queried" == grub-efi-amd64-bin ]]; then
            source='https://foreign.example trixie/main amd64 Packages'
        fi
        if [[ "$test_apt_case" == efi-modules-bin-mismatch && "$queried" == grub-efi-amd64-bin ]] ||
            [[ "$test_apt_case" == efi-modules-unsigned-mismatch && "$queried" == grub-efi-amd64-unsigned ]]; then
            policy_version=2.12-10
        fi
        printf '%s:\n  Installed: (none)\n  Candidate: %s\n  Version table:\n     %s 500\n        500 %s\n' "$queried" "$policy_version" "$policy_version" "$source"
        if [[ "$test_apt_case" == mixed-dependency && "$queried" == libefiboot1 ]] ||
            [[ "$test_apt_case" == efi-modules-mixed && "$queried" == grub-efi-amd64-unsigned ]]; then
            printf '        500 https://foreign.example trixie/main amd64 Packages\n'
        fi
    }
    _kernel_grub_install_plan_packages || test_fail 'official GRUB and dependency plan rejected'
    assert_equal 5 "${#KERNEL_GRUB_INSTALL_ARGS[@]}" 'complete package and dependency change list exposed'
    assert_equal 2.12-9 "${KERNEL_GRUB_INSTALL_EXPECTED_VERSIONS[libefiboot1]}" 'dependency exact version retained for post-install verification'
    output="$(kernel_join_values "${KERNEL_GRUB_INSTALL_ARGS[@]}")"
    assert_contains "$output" 'grub-pc=2.12-9' 'grub-pc version pinned'
    assert_contains "$output" 'libefiboot1=2.12-9' 'dependency version pinned'

    for test_apt_case in foreign-request foreign-dependency mixed-dependency untrusted-index; do
        assert_rejected "$test_apt_case cannot authorize package installation" _kernel_grub_install_plan_packages
    done
    test_apt_case=removal
    assert_status 30 'APT removal operation rejected' _kernel_grub_install_plan_packages
    test_apt_case=orphan-conf
    assert_status 30 'unplanned dpkg configuration rejected' _kernel_grub_install_plan_packages
    test_apt_case=kernel-change
    assert_status 3 'GRUB transaction cannot change kernel packages' _kernel_grub_install_plan_packages
    test_apt_case=efi-change
    assert_status 3 'BIOS installation cannot replace another boot backend' _kernel_grub_install_plan_packages
    test_apt_case=failure
    assert_status 20 'failed APT simulation never becomes an install plan' _kernel_grub_install_plan_packages

    test_apt_case='efi-modules-valid'
    KERNEL_PKG_STATUS=(['grub-common']='ii ' ['grub-efi-amd64-bin']='ii ')
    KERNEL_PKG_VERSION=(['grub-common']=2.12-8 ['grub-efi-amd64-bin']=2.12-8)
    _kernel_grub_install_plan_packages || test_fail 'installed EFI modules may follow the necessary matching official grub-common upgrade'
    assert_equal 7 "${#KERNEL_GRUB_INSTALL_ARGS[@]}" 'complete plan includes the required EFI binary and unsigned dependency versions'
    assert_equal 2.12-9 "${KERNEL_GRUB_INSTALL_EXPECTED_VERSIONS['grub-efi-amd64-bin']}" 'existing EFI binary upgrade is pinned'
    assert_equal 2.12-9 "${KERNEL_GRUB_INSTALL_EXPECTED_VERSIONS['grub-efi-amd64-unsigned']}" 'official unsigned dependency matches its binary version'
    KERNEL_PKG_STATUS['grub-efi-amd64-bin']='hi '
    _kernel_grub_install_plan_packages || test_fail 'configured held EFI binary still proves an existing backend module package'
    KERNEL_PKG_STATUS['grub-efi-amd64-bin']='ii '
