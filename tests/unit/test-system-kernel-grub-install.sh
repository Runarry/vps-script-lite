test_debconf_snapshot_is_read_only() (
    local mode=registered output log="$TEST_TEMP/debconf-reads.log"
    reset_fixture
    : >"$log"
    debconf-communicate() {
        local request
        request="$(cat)"
        printf '%s\n' "$request" >>"$log"
        [[ "$request" == GET* && "$request" == *FGET* ]] || test_fail 'snapshot attempted something other than question reads'
        if [[ "$mode" == absent ]]; then
            printf '10 question does not exist\n10 question does not exist\n'
            return 10
        elif [[ "$mode" == failure ]]; then
            printf '100 database unavailable\n'
            return 1
        fi
        if [[ "$request" == 'GET grub-pc/cloud_style_installation'* ]]; then
            printf '0 true\n0 true\n'
        else
            printf '0 /dev/old-wrong-disk\n0 true\n'
        fi
    }
    output="$(_kernel_grub_install_debconf_snapshot)" || test_fail 'registered debconf questions could not be snapshotted'
    assert_contains "$output" '/dev/old-wrong-disk' 'snapshot preserves prior target for recovery'
    assert_contains "$output" 'grub-pc/install_devices_failed_upgrade' 'snapshot includes failure handling configuration'
    assert_contains "$output" $'grub-pc/cloud_style_installation\n0 true\n0 true' 'snapshot preserves Ubuntu cloud auto-selection value and seen state'
    [[ "$(<"$log")" != *SET* && "$(<"$log")" != *REGISTER* ]] || test_fail 'read-only snapshot modified the debconf database'
    mode=absent
    output="$(_kernel_grub_install_debconf_snapshot)" || test_fail 'absent grub-pc questions should not require package installation'
    assert_contains "$output" '10 question does not exist' 'snapshot distinguishes absent questions'
    mode=failure
    assert_status 3 'unreadable debconf database prevents a complete backup plan' _kernel_grub_install_debconf_snapshot
)

