test_transaction_write_boundaries() (
    local mode=success prepare_count=0 status output log="$TEST_TEMP/grub-transaction.log"
    reset_fixture
    vps_cmd_require_root() { return 0; }
    kernel_take_lock() { printf 'lock\n' >>"$log"; }
    kernel_cleanup() { printf 'cleanup\n' >>"$log"; }
    kernel_confirm_action() {
        printf 'confirm\n' >>"$log"
        [[ "$mode" != cancel ]] || return 130
    }
    _kernel_grub_install_prepare() {
        prepare_count=$((prepare_count + 1))
        printf 'prepare:%s\n' "$prepare_count" >>"$log"
        KERNEL_GRUB_INSTALL_DISK=/dev/vda
        KERNEL_GRUB_INSTALL_PLAN_SIGNATURE=baseline
        KERNEL_GRUB_INSTALL_DEFAULT_RELEASE=6.12.12-amd64
        if [[ "$mode" == confirm-drift ]] && ((prepare_count >= 2)); then
            KERNEL_GRUB_INSTALL_PLAN_SIGNATURE=changed
        elif [[ "$mode" == backup-drift ]] && ((prepare_count >= 3)); then
            KERNEL_GRUB_INSTALL_PLAN_SIGNATURE=changed
        fi
    }
    _kernel_grub_install_show_plan() { printf 'fixture complete plan\n'; }
    _kernel_grub_install_backup() {
        printf 'backup\n' >>"$log"
        [[ "$mode" != backup-failure ]] || return 20
        KERNEL_GRUB_INSTALL_BACKUP="$TEST_TEMP/transaction-$mode"
        mkdir -p "$KERNEL_GRUB_INSTALL_BACKUP"
        printf 'backup-complete\n' >"$KERNEL_GRUB_INSTALL_BACKUP/stage"
        printf 'fixture recovery evidence\n' >"$KERNEL_GRUB_INSTALL_BACKUP/RECOVERY.txt"
    }
    _kernel_grub_install_execute() {
        printf 'execute\n' >>"$log"
        [[ "$mode" != install-failure ]] || return 20
        if [[ "$mode" == interrupted ]]; then
            # Signal only the currently running fixture transaction subshell.
            kill -TERM "$BASHPID"
            return 99
        fi
        printf 'complete-pending-reboot\n' >"$KERNEL_GRUB_INSTALL_BACKUP/stage"
    }

    : >"$log"
    VPSCTL_DRY_RUN=1
    output="$(kernel_install_grub 2>&1)" || test_fail 'dry-run failed'
    assert_equal 'prepare:1' "$(<"$log")" 'dry-run performs only read-only preparation'
    assert_contains "$output" '未刷新 APT' 'dry-run states zero-write behavior'
    [[ ! -e "$KERNEL_GRUB_BACKUP_ROOT" ]] || test_fail 'dry-run created a backup directory'
    VPSCTL_DRY_RUN=0

    for mode in cancel confirm-drift backup-failure backup-drift install-failure interrupted success; do
        : >"$log"
        status=0
        output="$(kernel_install_grub 2>&1)" || status=$?
        case "$mode" in
            cancel)
                assert_equal 130 "$status" 'cancel returns before lock and backup'
                assert_equal $'prepare:1\nconfirm' "$(<"$log")" 'cancel does not prepare a mutation'
                ;;
            confirm-drift)
                assert_equal 3 "$status" 'confirmation-time drift rejected'
                assert_equal $'prepare:1\nconfirm\nlock\nprepare:2\ncleanup' "$(<"$log")" 'confirmation drift prevents backup and writes'
                ;;
            backup-failure)
                assert_equal 20 "$status" 'backup failure is pre-install failure'
                [[ "$(<"$log")" != *execute* ]] || test_fail 'backup failure reached package or disk writes'
                ;;
            backup-drift)
                assert_equal 3 "$status" 'backup-time drift rejected'
                [[ "$(<"$log")" != *execute* ]] || test_fail 'backup-time drift reached installation'
                [[ -f "$TEST_TEMP/transaction-$mode/RECOVERY.txt" ]] || test_fail 'backup-time drift discarded recovery evidence'
                ;;
            install-failure | interrupted)
                assert_equal 30 "$status" "$mode is partial completion once writes could have begun"
                assert_contains "$output" '部分完成' "$mode describes incomplete installation accurately"
                [[ -f "$TEST_TEMP/transaction-$mode/result" && -f "$TEST_TEMP/transaction-$mode/RECOVERY.txt" ]] || test_fail "$mode lost recovery evidence"
                ;;
            success)
                assert_equal 0 "$status" 'successful validated installation'
                assert_equal $'prepare:1\nconfirm\nlock\nprepare:2\nbackup\nprepare:3\nexecute\ncleanup' "$(<"$log")" 'complete backup and final drift check precede writes'
                assert_contains "$output" '待重启验证' 'success does not claim actual firmware boot verification'
                ;;
        esac
    done
)

