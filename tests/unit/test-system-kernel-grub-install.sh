write_grub_fixture() {
    local selector="$1" release
    printf "GRUB_DEFAULT='%s'\nGRUB_SAVEDEFAULT=false\n" "$selector" >"$KERNEL_GRUB_DEFAULT_FILE"
    cat >"$KERNEL_GRUB_CFG" <<EOF
# DO NOT EDIT THIS FILE
# generated by grub-mkconfig
set default="$selector"
### BEGIN /etc/grub.d/10_linux ###
menuentry 'Debian GNU/Linux' \$menuentry_id_option 'gnulinux-simple-UUID' {
    linux /boot/vmlinuz-7.2.4-x64v3-xanmod1 root=UUID=root-a ro
}
submenu 'Advanced options for Debian GNU/Linux' \$menuentry_id_option 'gnulinux-advanced-UUID' {
    menuentry 'Debian GNU/Linux, with Linux 7.2.4-x64v3-xanmod1' \$menuentry_id_option 'gnulinux-7.2.4-x64v3-xanmod1-advanced-UUID' {
        linux /boot/vmlinuz-7.2.4-x64v3-xanmod1 root=UUID=root-a ro
    }
    menuentry 'Debian GNU/Linux, with Linux 6.12.12-amd64' \$menuentry_id_option 'gnulinux-6.12.12-amd64-advanced-UUID' {
        linux /boot/vmlinuz-6.12.12-amd64 root=UUID=root-a ro
    }
}
### END /etc/grub.d/10_linux ###
EOF
    write_env_fixture
    for release in "${KERNEL_RELEASES[@]}"; do
        mkdir -p "$KERNEL_MODULES_DIR/$release/kernel"
        printf 'fixture image %s\n' "$release" >"$KERNEL_BOOT_DIR/vmlinuz-$release"
        printf 'fixture initrd %s\n' "$release" >"$KERNEL_BOOT_DIR/initrd.img-$release"
        printf 'fixture module\n' >"$KERNEL_MODULES_DIR/$release/kernel/test.ko"
    done
}

write_env_fixture() {
    python3 - "$KERNEL_GRUB_ENV" "$@" <<'PY'
import sys

content = ("# GRUB Environment Block\n" + "".join(line + "\n" for line in sys.argv[2:])).encode()
assert len(content) < 1024
with open(sys.argv[1], "wb") as stream:
    stream.write(content + b"#" * (1024 - len(content)))
PY
}

