test_execute_debconf_isolation_and_readback() (
    local test_execute_case=success package updates=0 status log="$TEST_TEMP/grub-execute.log" seed="$TEST_TEMP/debconf-current" output
    local expected_next='gnulinux-advanced-UUID>gnulinux-7.2.4-x64v3-xanmod1-advanced-UUID'
    local expected_default='gnulinux-advanced-UUID>gnulinux-6.12.12-amd64-advanced-UUID'
    kernel_inventory_load() { return 0; }
    kernel_grub_probe_active() { return 0; }
    # These names satisfy the post-install tool gate. The execution dispatcher
    # below intercepts every mutating command and uses only fixture files.
    grub-install() { test_fail 'unit test reached a real disk writer'; }
    update-grub() { test_fail 'unit test reached a host GRUB generator'; }
    grub-editenv() {
        [[ "${2:-}" == list ]] || test_fail 'unexpected direct environment write'
