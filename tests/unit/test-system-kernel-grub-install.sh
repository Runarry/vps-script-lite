                [[ "$test_execute_case" != boot-drift ]] || printf 'unexpected initrd replacement\n' >>"$KERNEL_BOOT_DIR/initrd.img-6.12.12-amd64"
                ;;
            grub-install)
                printf 'disk:%s\n' "${!#}" >>"$log"
                assert_equal /dev/vda "${!#}" 'explicit GRUB installation targets only the confirmed disk'
                for argument in "$@"; do
                    [[ "$argument" != --force && "$argument" != --force=* ]] || test_fail 'explicit GRUB installation permits blocklist forcing'
                done
                [[ "$test_execute_case" != grub-failure ]] || return 1
                ;;
            update-grub)
                printf 'update\n' >>"$log"
                updates=$((updates + 1))
                if [[ -f "$KERNEL_GRUB_DROPIN" ]]; then
                    selected="$(sed -n "s/^GRUB_DEFAULT='\(.*\)'$/\1/p" "$KERNEL_GRUB_DROPIN")"
                fi
                [[ "$test_execute_case" != readback-failure || "$updates" != 2 ]] || selected=0
                sed -i "s|^set default=.*|set default=\"$selected\"|" "$KERNEL_GRUB_CFG"
                ;;
            grub-editenv)
                assert_equal "$KERNEL_GRUB_ENV" "$2" 'environment command targets fixture-owned path'
                printf 'env:%s\n' "$3" >>"$log"
                case "$3" in
                    create | unset) write_env_fixture ;;
                    set) write_env_fixture "$4" ;;
                    *) return 97 ;;
                esac
                ;;
            *) test_fail "unexpected mutating command in BIOS GRUB transaction: $1" ;;
        esac
    }

    for test_execute_case in success missing-env apt-failure grub-failure readback-failure table-drift debconf-drift debconf-flag-drift cloud-auto-drift boot-drift; do
        reset_fixture
        : >"$log"
