test_fail() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

assert_equal() {
    [[ "$1" == "$2" ]] || test_fail "$3: expected '$1', got '$2'"
}

assert_contains() {
    [[ "$1" == *"$2"* ]] || test_fail "$3: missing '$2' in '$1'"
}

assert_status() {
    local expected="$1" message="$2" status=0
    shift 2
    "$@" >"$TEST_TEMP/last-output" 2>&1 || status=$?
    assert_equal "$expected" "$status" "$message ($(cat "$TEST_TEMP/last-output"))"
}

assert_rejected() {
    local message="$1" status=0
    shift
    "$@" >"$TEST_TEMP/last-output" 2>&1 || status=$?
    ((status != 0)) || test_fail "$message: unsafe fixture was accepted"
}

